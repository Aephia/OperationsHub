#!/usr/bin/env node

/**
 * Write JSON/stat-descriptions.json - the ship stat descriptions Ship Explorer shows as tooltips
 * ("Cargo Capacity: The amount of cargo this ship can hold. Unit: CU").
 *
 * The descriptions ship inside the SAGE uber-export at shipConfigurations.statDescriptions, so
 * split-uber-export.js writes this file on every normal import. It can also be run on its own:
 *
 *   node RefreshData/stat-descriptions.js <uber-export.json>
 *   node RefreshData/stat-descriptions.js --ses     # download from the live SAGE Editor Suite instead
 *
 * The SES file (Ship Config Lite, ~33 MB) carries the same statDescriptions section at its root;
 * on 2026-09-13 all 78 entries were identical to the 2026-09-11 uber-export.
 *
 * The text is treated as untrusted: every value must be a short plain string (no markup, no
 * control characters) or nothing is written and the previous file is kept. Ship Explorer also
 * renders it with textContent, never innerHTML.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const SES_URL = 'https://ses.staratlas.com/SAGE%20Editor%20Suite/Ship%20Configurator/ship_configurations-combatv5.json';
const SHIP_EXPLORER_APP = path.join(ROOT_DIR, 'ShipExplorer', 'app.js');

// Ship Explorer stat key -> source key, where the two name the same stat differently
const ALIASES = {
    sdu_per_scan: 'sduPerScan',
    passengers: 'passenger_capacity'
};

const MIN_ENTRIES = 50;
const MAX_LENGTH = 500;
const UNSAFE = /[<>\x00-\x1f\x7f]/;

function validate(raw) {
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) {
        throw new Error('no statDescriptions object found - source layout changed?');
    }
    const entries = Object.entries(raw);
    if (entries.length < MIN_ENTRIES) {
        throw new Error(`only ${entries.length} descriptions (expected >= ${MIN_ENTRIES}) - refusing to overwrite`);
    }
    const bad = entries.filter(([key, text]) =>
        typeof text !== 'string' || !text.trim() || text.length > MAX_LENGTH || UNSAFE.test(text) || UNSAFE.test(key)
    );
    if (bad.length) {
        throw new Error(`unsafe or malformed descriptions: ${bad.map(([k]) => k).slice(0, 10).join(', ')}`);
    }
}

// Stat keys Ship Explorer renders, read from its own definitions, for the coverage report
function shipExplorerStats() {
    const src = fs.readFileSync(SHIP_EXPLORER_APP, 'utf8');
    return [...src.matchAll(/\{ key: '([^']+)', label: '([^']+)'/g)].map(m => ({ key: m[1], label: m[2] }));
}

/**
 * Validate and write the descriptions. Throws (writing nothing) on bad input.
 * @param raw    the statDescriptions object from the source
 * @param source human-readable origin recorded in the file, e.g. "SAGE uber-export 2026-09-11"
 * @param outDir directory holding stat-descriptions.json (default JSON/)
 */
function writeStatDescriptions(raw, source, outDir = path.join(ROOT_DIR, 'JSON')) {
    validate(raw);

    const descriptions = {};
    Object.keys(raw).sort().forEach(key => { descriptions[key] = raw[key].trim(); });
    Object.entries(ALIASES).forEach(([ours, theirs]) => {
        if (descriptions[theirs] && !descriptions[ours]) descriptions[ours] = descriptions[theirs];
    });

    const stats = shipExplorerStats();
    const missing = stats.filter(s => !descriptions[s.key]);
    console.log(`stat descriptions: ${Object.keys(raw).length} from ${source}, ` +
        `${stats.length - missing.length}/${stats.length} Ship Explorer stats covered`);
    missing.forEach(s => console.warn(`⚠️  no description for ${s.key} (${s.label})`));

    const output = {
        source,
        generatedAt: new Date().toISOString(),
        note: 'Generated by RefreshData/stat-descriptions.js - do not edit by hand.',
        descriptions
    };

    // Temp file + rename, so a failed write never leaves a truncated file behind
    const outFile = path.join(outDir, 'stat-descriptions.json');
    const tmp = `${outFile}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(output, null, 2) + '\n', 'utf8');
    fs.renameSync(tmp, outFile);
    console.log(`wrote stat-descriptions.json (${Object.keys(descriptions).length} entries)`);
}

module.exports = { writeStatDescriptions };

if (require.main === module) {
    (async () => {
        const arg = process.argv[2];
        if (!arg) {
            console.error('usage: node RefreshData/stat-descriptions.js <uber-export.json> | --ses');
            process.exit(2);
        }
        if (arg === '--ses') {
            console.log(`downloading ${SES_URL}`);
            const response = await fetch(SES_URL);
            if (!response.ok) throw new Error(`download failed: HTTP ${response.status}`);
            const data = await response.json();
            writeStatDescriptions(data.statDescriptions, 'SAGE Editor Suite (ses.staratlas.com, Ship Config Lite)');
        } else {
            const data = JSON.parse(fs.readFileSync(arg, 'utf8'));
            // uber-export nests it under shipConfigurations; a raw SES configuration file has it at the root
            const raw = data.shipConfigurations?.statDescriptions ?? data.statDescriptions;
            const exportDate = data.meta?.exportDate;
            writeStatDescriptions(raw, exportDate ? `SAGE uber-export ${String(exportDate).slice(0, 10)}` : path.basename(arg));
        }
    })().catch(error => {
        console.error(`❌ stat descriptions FAILED: ${error.message}`);
        process.exit(1);
    });
}
